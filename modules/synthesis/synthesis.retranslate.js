// modules/synthesis/synthesis.retranslate.js
//
// Догон переводов: статья, у которой перевода нет, сама его не получит.
//
// ПОЧЕМУ ЭТО НУЖНО. Перевод запускается один раз — сразу после генерации,
// вызовом «выстрелил и забыл» (synthesis.service.js). У него нет ни
// очереди, ни повтора, ни следа в базе. Значит любая из обычных причин —
// перезапуск процесса посреди перевода, таймаут модели, выключенный на
// ночь тумблер, упавший лимит токенов — оставляет статью непереведённой
// НАВСЕГДА: ночная задача берёт только свежие, а к вчерашней уже никто не
// возвращается.
//
// Так и вышло: статьи по 31 августа переведены на все языки, а вышедшие
// 9 и 10 сентября — нет. Ровно те, что появились после перезапусков
// движка. На арабской версии сайта они стоят русскими заголовками среди
// арабских.
//
// ЧТО ДЕЛАЕТ. Раз в сутки ищет опубликованные статьи, где перевода нет
// или он устарел, и переводит несколько штук. Это тот же разбор, что в
// scripts/retranslateMissing.js, — но сам по расписанию, а не когда
// кто-то заметит и запустит руками.
//
// ПОЧЕМУ ПО ДВЕ ЗА РАЗ. Перевод статьи — четыре длинных генерации, это
// дорого. Выпускается примерно одна статья в сутки, так что двух за
// прогон хватает и на текущий поток, и на медленный разбор накопившегося.
// Предел меняется переменной SYNTHESIS_RETRANSLATE_LIMIT.

import Synthesis from "./synthesis.model.js";
import { translateAllLocales } from "./synthesis.controller.js";
import { isEnabled } from "../settings/jobSwitches.service.js";

const ЯЗЫКИ = ["en", "az", "tr", "ar"];

/** Каких языков не хватает и какие переводы устарели. */
function чегоНеХватает(статья) {
  const переводы = статья.translations || {};
  const дописана = статья.finishedAt ? new Date(статья.finishedAt) : null;

  const нет = ЯЗЫКИ.filter((l) => !переводы[l]?.title);

  /* Устаревший опаснее отсутствующего: отсутствие видно сразу, а перевод,
     сделанный с обрезанного текста, выглядит целым — русская статья
     дочитывается до конца, арабская обрывается там, где обрывался
     исходник. Признак — перевод СТАРШЕ, чем дописывание статьи. */
  const устарел = дописана
    ? ЯЗЫКИ.filter((l) => {
        const когда = переводы[l]?.translatedAt;
        return когда && new Date(когда) < дописана;
      })
    : [];

  return { нет, устарел, нужен: нет.length + устарел.length > 0 };
}

export async function догнатьПереводы({ предел } = {}) {
  const limit =
    предел || Number(process.env.SYNTHESIS_RETRANSLATE_LIMIT) || 2;

  // Тумблер тот же, что у перевода при генерации: выключили перевод —
  // выключен и догон, иначе он бы обходил запрет с чёрного хода.
  if (!(await isEnabled("translation"))) {
    console.log("⏸  Догон переводов: перевод выключен в панели — пропускаем");
    return { обработано: 0, пропущено: true };
  }

  // translations нужны целиком только для проверки наличия ключей, но
  // выбирать их с телами — мегабайты. Берём агрегацией одни ключи и даты.
  const кандидаты = await Synthesis.aggregate([
    { $match: { status: "published" } },
    { $sort: { createdAt: -1 } },
    {
      $project: {
        title: 1,
        finishedAt: 1,
        translations: {
          $arrayToObject: {
            $map: {
              input: { $objectToArray: { $ifNull: ["$translations", {}] } },
              as: "t",
              in: {
                k: "$$t.k",
                v: {
                  title: { $cond: ["$$t.v.title", true, false] },
                  translatedAt: "$$t.v.translatedAt",
                },
              },
            },
          },
        },
      },
    },
  ]);

  const ждут = кандидаты
    .map((a) => ({ a, ...чегоНеХватает(a) }))
    .filter((x) => x.нужен);

  if (!ждут.length) {
    console.log("✅ Догон переводов: непереведённых статей нет");
    return { обработано: 0 };
  }

  console.log(
    `🈯 Догон переводов: ждут ${ждут.length}, берём ${Math.min(limit, ждут.length)}`,
  );

  let обработано = 0;
  for (const { a, нет, устарел } of ждут.slice(0, limit)) {
    const метки = [
      нет.length ? `нет: ${нет.join(",")}` : "",
      устарел.length ? `устарел: ${устарел.join(",")}` : "",
    ]
      .filter(Boolean)
      .join("; ");
    console.log(`   → ${String(a.title).slice(0, 60)} (${метки})`);

    try {
      // Модель целиком: translateAllLocales читает body.
      const статья = await Synthesis.findById(a._id);
      if (статья) await translateAllLocales(статья);
      обработано += 1;
    } catch (err) {
      console.error(`   ✖ ${a._id}: ${err.message}`);
    }
  }

  console.log(`✅ Догон переводов: обработано ${обработано}`);
  return { обработано, ждали: ждут.length };
}

export default догнатьПереводы;
