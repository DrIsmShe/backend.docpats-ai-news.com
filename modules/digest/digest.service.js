// modules/digest/digest.service.js
//
// Как из чужой публикации получается наш дайджест.
//
// ГЛАВНОЕ ПРАВИЛО, РАДИ КОТОРОГО ВСЁ ЗАТЕВАЛОСЬ: изложение пишется ОТ
// ФАКТОВ, а не пересказом первого абзаца. Пересказ чужого текста — это
// производное произведение, и мы вернулись бы туда, откуда ушли. Поэтому
// модели даётся не «перескажи», а «ответь на четыре вопроса»: что
// изучали, на ком, что получилось, что это значит для практики.
//
// Проверить результат просто: если изложение начинается словами издания —
// оно не годится, и такая проверка здесь есть.
//
// ПОЧЕМУ ОДИН ВЫЗОВ НА ПЯТЬ ЯЗЫКОВ. Раньше перевод новости запускался при
// открытии читателем и переводил до 8000 знаков полного текста — отдельно
// на каждый язык. Здесь текста 400–600 знаков, и все пять языков просятся
// одним запросом: это дешевле, чем вызов плюс четыре перевода, а расход
// известен в момент выпуска, а не зависит от того, кто что откроет.

import Anthropic from "@anthropic-ai/sdk";
import News from "../news/news.model.js";
import DigestItem, { ЯЗЫКИ_ДАЙДЖЕСТА } from "./digest.model.js";
import { anthropicModel } from "../../config/ai.js";
import { оценитьЗначимость } from "../ingestion/evidenceScore.js";

const client = new Anthropic({ timeout: 120000, maxRetries: 2 });

/* Сколько текста оригинала показываем модели. Четырёх тысяч знаков
   хватает, чтобы понять суть работы: у научной статьи главное — в
   аннотации и выводах, а не в середине. Больше — деньги без пользы. */
const ЗНАКОВ_ИСТОЧНИКА = 4000;

/* Сколько раз возвращаться к сорвавшемуся материалу. Три попытки
   разделяют временную беду (таймаут, 429, оборванный ответ) и то, из чего
   изложения не выйдет никогда. */
const ПОТОЛОК_ПОПЫТОК = 3;

const ЯЗЫКИ_ПОДПИСИ = {
  ru: "русском",
  en: "английском",
  az: "азербайджанском",
  tr: "турецком",
  ar: "арабском",
};

/** Разбор JSON из ответа модели: она любит обрамлять его пояснениями. */
function разобратьJson(сырое) {
  if (!сырое) throw new Error("пустой ответ модели");
  const текст = String(сырое).trim();
  const начало = текст.indexOf("{");
  const конец = текст.lastIndexOf("}");
  if (начало === -1 || конец === -1) throw new Error("в ответе нет JSON");
  return JSON.parse(текст.slice(начало, конец + 1));
}

/** Тело новости из архива: оно есть не всегда, и это нормально. */
function телоНовости(новость) {
  const т = String(новость.content || "").trim();
  return т.length > 200 ? т : "";
}

/**
 * Написать изложение на пяти языках.
 * Возвращает { ru: {title, intro}, en: {...}, … }.
 */
export async function написатьИзложение(новость) {
  const источник = [
    новость.title,
    новость.aiSummaryShort || новость.summary,
    телоНовости(новость),
  ]
    .filter(Boolean)
    .join("\n\n")
    .slice(0, ЗНАКОВ_ИСТОЧНИКА);

  const языки = ЯЗЫКИ_ДАЙДЖЕСТА.map(
    (к) =>
      `"${к}": { "title": "заголовок на ${ЯЗЫКИ_ПОДПИСИ[к]}", "intro": "изложение на ${ЯЗЫКИ_ПОДПИСИ[к]}" }`,
  ).join(",\n  ");

  const запрос = [
    "Ниже — научная публикация из медицинского издания.",
    "",
    "Напиши КРАТКОЕ ИЗЛОЖЕНИЕ для врача: 3-4 предложения, отвечающих на вопросы —",
    "что изучали, на ком (дизайн и выборка), что получилось, что это значит для",
    "практики.",
    "",
    "ЖЁСТКИЕ ТРЕБОВАНИЯ:",
    "- Пиши СВОИМИ СЛОВАМИ от фактов. НЕ пересказывай первый абзац и не",
    "  переписывай аннотацию — это чужой текст, воспроизводить его нельзя.",
    '- Не начинай словами "Background", "Objective", "В исследовании" и не',
    "  копируй формулировки источника.",
    "- Не делай выводов, которых нет в работе, и не давай клинических",
    "  рекомендаций от себя.",
    "- Заголовок — свой, короткий, по сути результата. Не копия заголовка издания.",
    "- Если из текста не понять сути, верни для каждого языка пустые строки.",
    "",
    "Верни ТОЛЬКО JSON без пояснений:",
    "{",
    "  " + языки,
    "}",
    "",
    "ПУБЛИКАЦИЯ:",
    источник,
  ].join("\n");

  /* Потолок ответа.
   *
   * Стояло 2000, и на длинных работах ответ обрывался посреди JSON —
   * разбор падал с «Expected ',' or '}' at position 4423», и материал
   * уходил в failed без внятной причины. Пять языков по 3-4 предложения
   * — это 1100-1500 токенов, но русский и арабский считаются дороже
   * английского, и запаса не хватало. 3000 покрывает худший случай. */
  const ответ = await client.messages.create({
    model: anthropicModel(),
    max_tokens: 3000,
    messages: [{ role: "user", content: запрос }],
  });

  /* Обрыв по лимиту отличаем от кривого JSON: это разные поломки, и
     чинятся они по-разному — первая потолком, вторая подсказкой. */
  if (ответ.stop_reason === "max_tokens") {
    throw new Error("ответ оборван по лимиту токенов");
  }

  const разобрано = разобратьJson(ответ.content?.[0]?.text || "");

  const тексты = {};
  for (const к of ЯЗЫКИ_ДАЙДЖЕСТА) {
    const т = разобрано[к] || {};
    тексты[к] = {
      title: String(т.title || "").trim(),
      intro: String(т.intro || "").trim(),
    };
  }
  return тексты;
}

/* Изложение годно, если написано хотя бы по-русски и не оказалось началом
   исходного текста. Вторая проверка — та самая защита от пересказа:
   совпадение первых слов означает, что модель переписала аннотацию
   вместо того, чтобы изложить работу. */
function годно(тексты, новость) {
  const ru = тексты?.ru?.intro || "";
  if (ru.length < 80) return { ok: false, почему: "изложение слишком короткое" };

  const исходное = String(новость.aiSummaryShort || новость.summary || "")
    .trim()
    .slice(0, 60)
    .toLowerCase();

  for (const к of ЯЗЫКИ_ДАЙДЖЕСТА) {
    const т = (тексты[к]?.intro || "").trim().slice(0, 60).toLowerCase();
    if (исходное && т && т === исходное) {
      return { ok: false, почему: "совпадает с текстом издания" };
    }
  }
  return { ok: true };
}

/** Ссылка раздела: тот же слаг, что у архивной записи. */
function слаг(новость) {
  return String(новость.slug || String(новость._id)).slice(0, 180);
}

/**
 * Собрать дайджест по одной новости.
 * Идемпотентна: повторный вызов на той же новости ничего не создаёт.
 */
export async function собратьЭлемент(новость) {
  /* Повтор для сорвавшихся.
   *
   * Провал записывается в базу — иначе молчаливый сбой был бы неотличим
   * от очереди. Но запись о провале сама по себе закрывала материалу
   * дорогу навсегда: следующий прогон видел «этот уже брали» и шёл
   * дальше. Причины провалов временные — оборванный по лимиту ответ,
   * таймаут, 429, — и повторить их стоит. Готовое (published) не
   * переписываем: платить второй раз за тот же текст незачем. */
  const уже = await DigestItem.findOne({ newsId: новость._id }).lean();
  if (уже && уже.status === "published") return { пропущено: true };
  if (уже && (уже.attempts || 0) >= ПОТОЛОК_ПОПЫТОК) {
    return { пропущено: true, почему: "исчерпаны попытки" };
  }

  if (!новость.canonicalUrl) {
    return { пропущено: true, почему: "нет ссылки на источник" };
  }

  let тексты = null;
  let ошибка = "";
  try {
    тексты = await написатьИзложение(новость);
    const проверка = годно(тексты, новость);
    if (!проверка.ok) {
      ошибка = проверка.почему;
      тексты = null;
    }
  } catch (err) {
    ошибка = err?.message || "ошибка модели";
  }

  /* Оценка значимости у архивных материалов чаще всего не проставлена:
     правила появились позже, и старые записи лежат с константой 50 и
     пустым уровнем. Считаем на месте — правила детерминированные, денег
     не стоят, а без оценки лента дайджеста не отличает метаанализ в
     Lancet от описания одного случая. */
  const естьОценка = новость.evidenceLevel && новость.importanceScore !== 50;
  const оценка = естьОценка
    ? {
        importanceScore: новость.importanceScore,
        evidenceLevel: новость.evidenceLevel,
        signals: новость.evidenceSignals || [],
      }
    : (() => {
        const о = оценитьЗначимость(новость);
        return {
          importanceScore: о.importanceScore,
          evidenceLevel: о.evidenceLevel,
          signals: о.signals || [],
        };
      })();

  const запись = {
    newsId: новость._id,
    slug: слаг(новость),
    originalTitle: новость.title || "",
    texts: тексты || {},
    canonicalUrl: новость.canonicalUrl,
    sourceName: новость.sourceName || "",
    specialty: новость.specialty || новость.categoryPrimary || "general",
    specialties: новость.specialties || [],
    tags: новость.tags || [],
    importanceScore: оценка.importanceScore,
    evidenceLevel: оценка.evidenceLevel,
    evidenceSignals: оценка.signals,
    journal: новость.journal || "",
    doi: новость.doi || "",
    pmid: новость.pmid || "",
    publishedAt: новость.publishedAt || новость.createdAt,
    status: тексты ? "published" : "failed",
    error: ошибка,
    attempts: (уже?.attempts || 0) + 1,
  };

  if (уже) {
    await DigestItem.updateOne({ _id: уже._id }, { $set: запись });
  } else {
    await DigestItem.create(запись);
  }

  return { создано: true, ошибка };
}

/**
 * Порция архива. Свежее разбирается раньше старого.
 *
 * Партиями, а не разом: 6554 материала за один прогон — это единовременный
 * расход и упор в лимиты модели. По сотне в сутки архив разбирается за два
 * месяца, и никакого пика.
 */
export async function собратьПорцию({ сколько = 100 } = {}) {
  /* Дубли отсеиваются здесь, а не после: один и тот же пресс-релиз
     приходит из четырёх источников, и дайджест бы его учетверил. */
  const кандидаты = await News.find(
    {
      status: "published",
      isDuplicate: { $ne: true },
      canonicalUrl: { $exists: true, $ne: "" },
    },
    {
      title: 1,
      summary: 1,
      aiSummaryShort: 1,
      content: 1,
      canonicalUrl: 1,
      sourceName: 1,
      specialty: 1,
      categoryPrimary: 1,
      specialties: 1,
      tags: 1,
      slug: 1,
      importanceScore: 1,
      evidenceLevel: 1,
      evidenceSignals: 1,
      journal: 1,
      doi: 1,
      pmid: 1,
      publishedAt: 1,
      createdAt: 1,
    },
  )
    .sort({ publishedAt: -1, createdAt: -1 })
    .limit(сколько * 6)
    .lean();

  /* Сверяемся только по этой выборке: тянуть все newsId дайджеста ради
     фильтра — лишний мегабайт на каждом прогоне. Сорвавшиеся в этот
     список не попадают — они вернутся в очередь и будут повторены. */
  const готовые = await DigestItem.find(
    {
      newsId: { $in: кандидаты.map((н) => н._id) },
      $or: [{ status: "published" }, { attempts: { $gte: ПОТОЛОК_ПОПЫТОК } }],
    },
    { newsId: 1 },
  ).lean();
  const уже = new Set(готовые.map((d) => String(d.newsId)));

  const очередь = кандидаты
    .filter((н) => !уже.has(String(н._id)))
    .slice(0, сколько);

  if (!очередь.length) {
    console.log("📰 Дайджест: новых материалов нет");
    return { обработано: 0 };
  }

  console.log(`📰 Дайджест: берём ${очередь.length} материалов`);

  /* Несколько материалов разом, а не строго по одному.
   *
   * Один вызов модели идёт 15-25 секунд, и сотня подряд — это больше
   * получаса; разбор всего архива в таком темпе растянулся бы на месяцы
   * не из-за денег, а из-за ожидания. Три потока укладывают ту же сотню
   * в десять минут.
   *
   * Почему три, а не двадцать: у модели есть лимит запросов в минуту, и
   * упереться в него значит получить 429 на половине порции. Три —
   * запас, который держит любой тариф. Правится через DIGEST_PARALLEL. */
  const потоков = Math.max(1, Math.min(Number(process.env.DIGEST_PARALLEL) || 3, 8));
  let готово = 0;
  let сбоев = 0;
  let следующий = 0;

  const работник = async () => {
    while (следующий < очередь.length) {
      const н = очередь[следующий++];
      try {
        const итог = await собратьЭлемент(н);
        if (итог.создано) {
          if (итог.ошибка) сбоев += 1;
          else готово += 1;
        }
      } catch (err) {
        сбоев += 1;
        console.error("   ✖", String(н._id).slice(-6), err?.message);
      }
    }
  };

  await Promise.all(Array.from({ length: потоков }, работник));

  console.log(`📰 Дайджест: готово ${готово}, не вышло ${сбоев}`);
  return { обработано: готово, сбоев };
}

export default собратьПорцию;
