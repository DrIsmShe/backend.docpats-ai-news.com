// modules/ingestion/evidenceScore.js
//
// Значимость материала и уровень доказательности — по признакам, которые
// уже лежат в записи, без обращения к модели.
//
// ЗАЧЕМ ЭТО ПОЯВИЛОСЬ. Поля importanceScore и evidenceLevel в схеме были с
// самого начала, но не заполнялись: у всех ста проверенных записей стояло
// importanceScore: 50 (значение по умолчанию) и пустой evidenceLevel.
// Обогащение ходило в модель и при любой ошибке возвращало те же
// константы из блока catch — результат неотличим от успешного прохода.
//
// Хуже того, поле не читалось НИГДЕ: ни сортировки, ни фильтра. А шесть
// источников для каждой синтез-статьи выбирались случайной перестановкой.
// То есть обзор собирался не из самых значимых исследований в теме, а из
// произвольных — и на вопрос «по какому критерию отобраны источники»
// честный ответ был «ни по какому».
//
// ПОЧЕМУ ПРАВИЛА, А НЕ МОДЕЛЬ. Материалов сотни в сутки; обращение к
// модели на каждый — это деньги и ещё одна точка отказа, которая уже один
// раз молча сломалась. Всё, что нужно для оценки, лежит в самой записи:
// тип исследования называется в заголовке и аннотации почти всегда,
// журнал известен, наличие DOI и PMID проверяется полем. Правила
// воспроизводимы, стоят ноль и не ломаются молча.
//
// ЧЕГО ЭТА ОЦЕНКА НЕ ДЕЛАЕТ. Не заменяет чтение врачом и не притворяется
// экспертной. Это порядок отбора, а не приговор материалу: она отвечает на
// вопрос «что показать раньше», а не «что верно».

/* Иерархия дизайнов исследований — та же, что в пирамиде доказательности.
   Порядок важен: ищем сверху вниз и берём первое совпадение, иначе
   «systematic review of case reports» посчитался бы серией случаев. */
const ДИЗАЙНЫ = [
  { вес: 40, уровень: "high", слова: [
    "meta-analysis", "metaanalysis", "meta analysis",
    "systematic review", "cochrane",
  ] },
  { вес: 34, уровень: "high", слова: [
    "randomised controlled", "randomized controlled", "randomised trial",
    "randomized trial", "double-blind", "double blind", "placebo-controlled",
    " rct ", "phase iii", "phase 3 trial",
  ] },
  { вес: 26, уровень: "moderate", слова: [
    "cohort study", "prospective cohort", "longitudinal study",
    "population-based", "registry study",
  ] },
  { вес: 20, уровень: "moderate", слова: [
    "case-control", "case control", "cross-sectional", "observational study",
  ] },
  { вес: 10, уровень: "low", слова: [
    "case report", "case series", "in vitro", "animal model",
    "mouse model", "rat model", "preprint",
  ] },
  { вес: 4, уровень: "low", слова: [
    "editorial", "commentary", "opinion", "perspective", "letter to the editor",
  ] },
];

/* Журналы, у которых порог рецензирования заметно выше среднего.
   Список намеренно короткий: это не рейтинг изданий, а поправка на
   несколько имён, узнаваемых в любой специальности. */
const ВЕДУЩИЕ_ЖУРНАЛЫ = [
  "lancet", "new england journal", "nejm", "jama", "bmj",
  "nature medicine", "nature", "science", "annals of internal medicine",
  "circulation", "journal of clinical oncology",
];

const содержит = (текст, слова) => слова.some((с) => текст.includes(с));

/**
 * @param {object} статья  title, summary, content, journal, doi, pmid, publishedAt
 * @returns {{ importanceScore: number, evidenceLevel: string, signals: string[] }}
 */
export function оценитьЗначимость(статья = {}) {
  const текст = ` ${[статья.title, статья.summary, статья.aiSummaryShort]
    .filter(Boolean)
    .join(" ")
    .toLowerCase()} `;
  const журнал = String(статья.journal || "").toLowerCase();

  const признаки = [];
  let балл = 30; // базовый: обычная публикация без особых признаков
  let уровень = "";

  // 1. Дизайн исследования — главный вклад.
  for (const д of ДИЗАЙНЫ) {
    if (содержит(текст, д.слова)) {
      балл += д.вес;
      уровень = д.уровень;
      признаки.push("дизайн:" + д.уровень);
      break;
    }
  }

  // 2. Журнал.
  if (ВЕДУЩИЕ_ЖУРНАЛЫ.some((ж) => журнал.includes(ж))) {
    балл += 12;
    признаки.push("журнал");
  }

  /* 3. Идентификаторы первоисточника. DOI и PMID означают, что за
     материалом стоит публикация, а не пересказ пересказа. */
  if (статья.doi) { балл += 6; признаки.push("doi"); }
  if (статья.pmid) { балл += 4; признаки.push("pmid"); }

  /* 4. Размер выборки. Числа с разделителями («13.5 million», «4,200
     patients») — признак работы на людях, а не на шести мышах. */
  const выборка = текст.match(
    /([\d][\d,. ]*)\s*(million|billion|thousand)?\s*(patients|participants|adults|children|subjects|people)/,
  );
  if (выборка) {
    /* «13.5 million patients» — число словом, а не цифрами. Без разбора
       множителя крупнейшее исследование выглядело бы как выборка из
       тринадцати человек. */
    const МНОЖИТЕЛЬ = { thousand: 1e3, million: 1e6, billion: 1e9 };
    const основа = parseFloat(String(выборка[1]).replace(/[, ]/g, "")) || 0;
    const число = Math.round(основа * (МНОЖИТЕЛЬ[выборка[2]] || 1));
    if (число >= 100000) { балл += 10; признаки.push("выборка:100k+"); }
    else if (число >= 1000) { балл += 6; признаки.push("выборка:1k+"); }
    else if (число >= 100) { балл += 3; признаки.push("выборка:100+"); }
  }

  /* 5. Свежесть. Медицинская новость стареет не мгновенно, но месячной
     давности материал в обзоре уступает вчерашнему при прочих равных. */
  const дата = статья.publishedAt || статья.createdAt;
  if (дата) {
    const дней = (Date.now() - new Date(дата).getTime()) / 86400000;
    if (дней <= 3) { балл += 8; признаки.push("свежесть:3д"); }
    else if (дней <= 14) { балл += 4; признаки.push("свежесть:14д"); }
    else if (дней > 180) { балл -= 6; признаки.push("старше полугода"); }
  }

  /* Уровень доказательности без опознанного дизайна не выдумываем:
     пустая строка честнее «moderate» наугад. Но если есть DOI и ведущий
     журнал — это как минимум не низкий уровень. */
  if (!уровень && статья.doi && признаки.includes("журнал")) {
    уровень = "moderate";
    признаки.push("уровень:по журналу");
  }

  return {
    importanceScore: Math.max(0, Math.min(100, Math.round(балл))),
    evidenceLevel: уровень,
    signals: признаки,
  };
}

/**
 * Перемешивание Фишера—Йетса.
 *
 * sort(() => Math.random() - 0.5) перестановки НЕ даёт: компаратор должен
 * быть непротиворечивым, а случайный таковым не является — результат
 * зависит от алгоритма сортировки движка и заметно смещён. Там, где
 * случайность нужна по существу, она должна быть настоящей.
 */
export function перемешать(список) {
  const копия = [...список];
  for (let i = копия.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [копия[i], копия[j]] = [копия[j], копия[i]];
  }
  return копия;
}

export default оценитьЗначимость;
