//
// Что не должно попадать в ленту врача.
//
// Источники отдают всё подряд: PLOS ONE — мультидисциплинарный журнал и
// публикует в том числе работы про коров, а PubMed присылает поправки и
// отзывы наравне с исследованиями. В ленте это выглядит одинаково: карточка с
// плашкой «научная статья».
//
// Самое важное здесь — RETRACTION. Отозванная работа это та, которую научное
// сообщество признало недостоверной; её выводы отменены. Показывать её врачу
// как новость хуже, чем не показывать ничего. На момент написания в базе
// лежало 112 таких.
//
// Правило одно на две задачи: отсев при загрузке и разовая чистка уже
// накопленного (scripts/hideJunk.js). Держать их в разных местах нельзя —
// разойдутся.

/**
 * Признаки, по которым материал не идёт в ленту.
 *
 * Все проверки — по НАЧАЛУ заголовка, а не по вхождению где угодно. Разница
 * принципиальная: «Retraction: Effects of…» это отзыв, а «Retraction of
 * consent in clinical trials» — исследование ПРО отзывы, и его убирать
 * незачем.
 */
const TITLE_RULES = [
  { reason: "retraction", re: /^\s*(retraction|retracted)\b/i },
  { reason: "correction", re: /^\s*(correction|corrigendum|erratum)\b/i },
  { reason: "concern", re: /^\s*expression of concern\b/i },
  { reason: "editorial", re: /^\s*editorial\b/i },
];

// ОТСЕВА «НЕ ПРО ЛЮДЕЙ» ЗДЕСЬ НЕТ — И ЭТО РЕШЕНИЕ, А НЕ УПУЩЕНИЕ.
//
// Первая версия отсекала заголовки со словами cattle, poultry, swine и
// подобными. Пробный прогон на живой базе показал, во что это обходится:
// под правило попала новость CDC «Listeria linked to ready-to-eat meat and
// poultry products» — вспышка листериоза У ЛЮДЕЙ. По той же логике исчезло бы
// «H5N1 in dairy cattle», а это одна из важнейших эпидемиологических тем.
//
// Названия животных в медицинском заголовке чаще означают источник заражения
// или доклиническую модель человеческой болезни, чем ветеринарию. Отделить
// одно от другого по ключевым словам нельзя, а цена ошибки несимметрична:
// спрятать вспышку опаснее, чем показать работу про коров. Правило убрано
// целиком — оно снимало 38 материалов и рисковало важными.
//
// Если возвращать — то по предметным рубрикам MeSH («Animals» без «Humans»),
// а не по словам в заголовке. У большинства источников их нет.

/**
 * Нужно ли убрать материал из ленты.
 *
 * @param {{title?: string}} article
 * @returns {{excluded: boolean, reason: string}}
 */
export function classifyForFeed(article = {}) {
  const title = String(article.title || "");

  for (const rule of TITLE_RULES) {
    if (rule.re.test(title)) return { excluded: true, reason: rule.reason };
  }

  return { excluded: false, reason: "" };
}

/** Человеческое объяснение — для отчётов скриптов и админки. */
export const REASON_LABELS = Object.freeze({
  retraction: "отозванная работа",
  correction: "поправка к другой работе",
  concern: "сомнение редакции в достоверности",
  editorial: "колонка редактора",
});

export default { classifyForFeed, REASON_LABELS };
