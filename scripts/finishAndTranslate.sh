#!/bin/bash
# Полный догон: сначала дописать все оборванные статьи, потом перевести.
#
# Порядок важен и обратному не подлежит: перевод дописанной статьи делается
# с полного текста. Если переводить раньше, работа уйдёт впустую — перевод
# останется обрезанным, и переводить придётся второй раз.
cd /var/www/backend.docpats-ai-news.com

echo "=========== ЭТАП 1: ДОПИСЫВАНИЕ ==========="
for i in 1 2 3 4 5; do
  echo ""
  echo "--- партия $i ---"
  node scripts/finishTruncated.js 15 || echo "партия $i прервалась"
done

echo ""
echo "=========== ЭТАП 2: ПЕРЕВОД ==========="
# Берём с запасом: скрипт сам отберёт те, где перевода нет или он устарел.
node scripts/retranslateMissing.js 100 || echo "перевод прервался"

echo ""
echo "=========== ДОГОН ЗАВЕРШЁН ==========="
